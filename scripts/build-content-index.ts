import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';

/**
 * Regenerates content/index.generated.ts — a slug → dynamic import map.
 *
 * Why generated rather than hand-written: 89 entries drift. Why generated
 * rather than an fs scan at runtime: Next's Node.js serverless bundles trace
 * static imports, and a runtime readdir over content/ would not be traced.
 * `npm run content:validate` fails if this file is stale.
 */

const ROOT = join(process.cwd(), 'content', 'lessons');

export function findLessonFiles(): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir).sort()) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry.endsWith('.ts') && !entry.endsWith('.test.ts')) out.push(full);
    }
  };
  walk(ROOT);
  return out;
}

export function slugFromFile(file: string): string {
  return file.split('/').pop()!.replace(/\.ts$/, '');
}

export function renderIndex(files: string[]): string {
  const entries = files
    .map((f) => {
      const rel = './' + relative(join(process.cwd(), 'content'), f).replace(/\.ts$/, '');
      return `  '${slugFromFile(f)}': () => import('${rel}'),`;
    })
    .join('\n');

  return `// Generated by \`npm run content:index\`. Do not edit by hand.
import type { LessonInput } from './schema';

type LessonModule = { default: LessonInput };

export const lessonModules: Record<string, () => Promise<LessonModule>> = {
${entries}
};

export const lessonSlugs = Object.keys(lessonModules);
`;
}

import { pathToFileURL } from 'node:url';

/** Only write when run directly — validate-content and seed import the helpers. */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const target = join(process.cwd(), 'content', 'index.generated.ts');
  const next = renderIndex(findLessonFiles());
  const current = (() => {
    try {
      return readFileSync(target, 'utf8');
    } catch {
      return '';
    }
  })();

  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('content/index.generated.ts is stale. Run: npm run content:index');
      process.exit(1);
    }
    console.log('Content index is up to date.');
  } else {
    writeFileSync(target, next);
    console.log(`Wrote content/index.generated.ts (${findLessonFiles().length} lessons).`);
  }
}
